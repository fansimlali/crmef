-- 1. جدول الأسئلة
create table if not exists public.questions (
    id text primary key,
    subject text not null,          -- رمز المادة: ma, fr, ar, sc, dma, dfr, dar, dsc, edu
    topic text not null,            -- المحور / الباب: مثل "قابلية القسمة"، "نظريات التعلم"
    question text not null,         -- نص السؤال
    options jsonb not null,         -- مصفوفة الخيارات ["خيار 1", "خيار 2", ...]
    correct_answer text not null,   -- الجواب الصحيح
    explanation text default '',    -- التعليل والتوضيح البيداغوجي
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. تفعيل سياسة الأمان RLS
alter table public.questions enable row level security;

-- 3. سياسات الوصول (Policies)
-- السماح لجميع الزوار بقراءة الأسئلة لاجتياز الاختبار
create policy "الجميع يمكنهم قراءة الأسئلة" 
on public.questions for select 
using (true);

-- السماح بإضافة وتحديث الأسئلة
create policy "السماح بإضافة الأسئلة" 
on public.questions for insert 
with check (true);

create policy "السماح بتعديل الأسئلة" 
on public.questions for update 
using (true);

create policy "السماح بحذف الأسئلة" 
on public.questions for delete 
using (true);

