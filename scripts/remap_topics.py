def build_map_norm():
    out = {}
    for subj, m in MAP.items():
        d = {}
        for k, v in m.items():
            nk = norm_key(k)
            if nk in d and d[nk] != v:
                print(f'⚠️ تصادم في {subj}: «{k}» و«{[x for x in m if norm_key(x)==nk][0]}»')
            d[nk] = v
        out[subj] = d
    return out


