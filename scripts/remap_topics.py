def norm_key(s):
    """تطبيع للمطابقة: علامات apostrophe، تطويل، الألف (ديداكتيك ↔ ديدكتيك)، مسافات."""
    s = str(s).replace('’', "'").replace('‘', "'").replace('ʼ', "'")
    s = s.replace('ـ', '').replace('\u00a0', ' ')
    s = re.sub(r'\s+', ' ', s).strip()
    s = s.replace('ا', '')          # «ديداكتيك» = «ديدكتيك»
    return s


def esc(s):
    return str(s).replace("'", "''")


